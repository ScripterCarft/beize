#!/usr/bin/env bash
# Resolves packages.txt against Ubuntu's snapshot of the date in ./snapshot
# and writes packages.lock: every package of the buildroot with its exact
# version, its file in Ubuntu's pool and that file's SHA-256 – what
# Cargo.lock is for crates. create.sh installs exactly the lock.
#
# Run after changing packages.txt, or with a newer ./snapshot for Ubuntu's
# updates. The checksums come from the snapshot's package indexes, which
# its InRelease files pin, which Ubuntu's archive key signs.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
snapshot=$(< "$here/snapshot")
mirror=https://snapshot.ubuntu.com/ubuntu/$snapshot
pockets=(resolute resolute-updates resolute-security)
packages=$(grep -vE '^\s*(#|$)' "$here/packages.txt" | paste -sd, -)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

sources=()
for pocket in "${pockets[@]}"; do
    sources+=("deb $mirror $pocket main universe")
done
mmdebstrap --simulate --verbose --variant=apt --components=main,universe \
    --include="$packages" --aptopt='Acquire::Check-Valid-Until "false"' \
    resolute /dev/null "${sources[@]}" > "$work/simulate.log" 2>&1 ||
    { tail -40 "$work/simulate.log" >&2; exit 1; }
# "Inst <package> (<version> <origins> [<arch>]) …"
sed -n 's/^Inst \([^ ]*\) (\([^ ]*\) [^[]*\[\([a-z0-9]\+\)\]).*/\1 \2 \3/p' "$work/simulate.log" |
    sort -u > "$work/resolved"

for pocket in "${pockets[@]}"; do
    curl -fsS -o "$work/$pocket.InRelease" "$mirror/dists/$pocket/InRelease"
    gpgv --quiet --keyring /usr/share/keyrings/ubuntu-archive-keyring.gpg \
        --output "$work/$pocket.Release" "$work/$pocket.InRelease"
    for component in main universe; do
        curl -fsS -o "$work/$pocket.$component.Packages.xz" \
            "$mirror/dists/$pocket/$component/binary-amd64/Packages.xz"
    done
done

python3 - "$work" "${pockets[@]}" > "$here/packages.lock" <<'PY'
import hashlib, lzma, re, sys
work, pockets = sys.argv[1], sys.argv[2:]
files = {}
for pocket in pockets:
    release = open(f"{work}/{pocket}.Release").read()
    sums = release.split("SHA256:\n", 1)[1]
    pinned = dict((m[2], m[0]) for m in re.findall(r"^ (\S+)\s+(\d+)\s+(\S+)$", sums, re.M))
    for component in ("main", "universe"):
        name = f"{component}/binary-amd64/Packages.xz"
        data = open(f"{work}/{pocket}.{component}.Packages.xz", "rb").read()
        if hashlib.sha256(data).hexdigest() != pinned[name]:
            sys.exit(f"{pocket} {name}: checksum differs from the signed InRelease")
        for stanza in lzma.decompress(data).decode().split("\n\n"):
            fields = dict(re.findall(r"^([A-Za-z0-9-]+): (.*)$", stanza, re.M))
            if "Package" in fields:
                key = (fields["Package"], fields["Version"], fields["Architecture"])
                files[key] = (fields["Filename"], fields["SHA256"])
print("# Generated by ci/buildroot/lock.sh – do not edit.")
print("# package version architecture pool-file sha256")
for line in open(f"{work}/resolved"):
    key = tuple(line.split())
    if key not in files:
        sys.exit(f"{' '.join(key)} is in no package index")
    print(*key, *files[key])
PY
echo "$(grep -vc '^#' "$here/packages.lock") packages locked in ci/buildroot/packages.lock" >&2
